--  2) CHECK constraints (idempotentes vía pg_constraint).
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_Centros_Nombre_NoVacio') THEN
        ALTER TABLE "Centros" ADD CONSTRAINT "CK_Centros_Nombre_NoVacio"
            CHECK (length(btrim("Nombre")) > 0);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_Centros_Codigo_NoVacio') THEN
        ALTER TABLE "Centros" ADD CONSTRAINT "CK_Centros_Codigo_NoVacio"
            CHECK (length(btrim("Codigo")) > 0);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_Usuarios_NombreCompleto_NoVacio') THEN
        ALTER TABLE "Usuarios" ADD CONSTRAINT "CK_Usuarios_NombreCompleto_NoVacio"
            CHECK (length(btrim("NombreCompleto")) > 0);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'CK_Usuarios_AccessFailedCount_NoNegativo') THEN
        ALTER TABLE "Usuarios" ADD CONSTRAINT "CK_Usuarios_AccessFailedCount_NoNegativo"
            CHECK ("AccessFailedCount" >= 0);
    END IF;
END $$;

-- -----------------------------------------------------------------------------
--  3) Unicidad de email a nivel BD.
--     Program.cs activa options.User.RequireUniqueEmail = true; aquí lo
--     hacemos cumplir también en la BD. (Los NULL no colisionan en PG, por lo
--     que se permiten varios usuarios sin email, igual que ASP.NET Identity.)
-- -----------------------------------------------------------------------------
