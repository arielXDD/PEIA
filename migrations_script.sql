-- -----------------------------------------------------------------------------
--  4) CONCURRENCIA OPTIMISTA REAL para "Centros".
--
--     El token "Version" (bytea, mapeado con IsRowVersion()) NO cambia solo en
--     PostgreSQL. Sin esto, dos procesos que editan el mismo Centro se pisan.
--     Con este trigger, cada INSERT/UPDATE asigna un valor nuevo y monótono;
--     EF Core compara el valor original en el WHERE de UPDATE: si otro proceso
--     ya lo cambió, afecta 0 filas y lanza DbUpdateConcurrencyException.
-- -----------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS "peia_row_version_seq" AS bigint;

CREATE OR REPLACE FUNCTION "peia_set_row_version"()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    -- int8send -> 8 bytes big-endian; siempre distinto y creciente.
    NEW."Version" := int8send(nextval('"peia_row_version_seq"'));
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS "trg_Centros_RowVersion" ON "Centros";
CREATE TRIGGER "trg_Centros_RowVersion"
    BEFORE INSERT OR UPDATE ON "Centros"
    FOR EACH ROW
    EXECUTE FUNCTION "peia_set_row_version"();

-- Backfill: cualquier fila existente con Version NULL queda con token válido.
UPDATE "Centros" SET "Version" = int8send(nextval('"peia_row_version_seq"'))
WHERE "Version" IS NULL;

