-- =============================================================================
--  PEIA - Script de migración inicial (PostgreSQL) - VERSIÓN ENDURECIDA
-- =============================================================================
--  Objetivos de robustez ("indestructible") y soporte de concurrencia
--  (varios procesos / múltiples instancias atacando la misma BD):
--
--   1. ATÓMICO         : todo el DDL corre en una sola transacción. Si algo
--                        falla, NO queda nada a medias (DDL transaccional de PG).
--   2. IDEMPOTENTE     : el script se puede re-ejecutar sin error. Sirve tanto
--                        para una BD vacía como para una donde EF Core ya creó
--                        las tablas (despliegues repetidos / reintentos).
--   3. CONCURRENCIA    : se ARREGLA el token de concurrencia optimista de
--                        "Centros". El mapeo IsRowVersion() -> bytea NO se
--                        autoincrementa en PostgreSQL (a diferencia de SQL
--                        Server), por lo que tal cual venía generado las
--                        actualizaciones concurrentes se pisaban entre sí
--                        (lost updates). Aquí un trigger BEFORE INSERT/UPDATE
--                        regenera "Version" en cada escritura -> EF detecta el
--                        conflicto y lanza DbUpdateConcurrencyException.
--   4. INTEGRIDAD      : defaults a nivel servidor (gen_random_uuid(), now()),
--                        CHECK constraints y unicidad de email/usuario para que
--                        la BD se defienda incluso ante inserciones por fuera de
--                        la aplicación.
--
--  Compatible con EF Core: se conservan exactamente los nombres de tablas,
--  columnas, claves e índices, y la fila de __EFMigrationsHistory.
-- =============================================================================

